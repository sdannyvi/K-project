def load_completed(path: Path) -> set[str]:
    if not path.exists():
        return set()
    completed: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        completed.add(str(row["run_id"]))
    return completed


def append_row(path: Path, row: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def chat(
    client: Any,
    model: str,
    condition: str,
    prompt: str,
    history: list[dict[str, str]] | None,
    rag_data: tuple[list[Any], Any] | None,
) -> tuple[str, list[dict[str, str]], list[str]]:
    sources: list[str] = []
    user_content = prompt
    if condition == "chatwithk":
        if rag_data is None:
            raise RuntimeError("ChatWithK requires a loaded RAG index")
        records, matrix = rag_data
        retrieved = retrieve_top_k(prompt, records, matrix, client, k_config.RAG_TOP_K)
        sources = [record.source_file for record, _score in retrieved]
        user_content = build_rag_user_message(prompt, retrieved)

    messages = [{"role": "system", "content": CONDITIONS[condition]}]
    if history:
        messages.extend(history)
    messages.append({"role": "user", "content": user_content})
    completion = client.chat.completions.create(
        model=model,
        temperature=0,
        max_tokens=450,
        messages=messages,
    )
    response = completion.choices[0].message.content or ""
    new_history = list(history or [])
    new_history.extend(
        [
            {"role": "user", "content": user_content},
            {"role": "assistant", "content": response},
        ]
    )
    return response, new_history, sources


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--conditions", nargs="+", choices=CONDITIONS, default=list(CONDITIONS))
    args = parser.parse_args()

    client = initialize_client()
    model = get_deployment()
    rag_data = load_index(k_config.K_INDEX_DIR)
    completed = load_completed(args.output)

    for item in POC_ITEMS:
        for condition in args.conditions:
            history: list[dict[str, str]] = []
            run_id = f"{item['id']}::{condition}::turn1"
            if run_id not in completed:
                started = time.monotonic()
                response, history, sources = chat(
                    client, model, condition, item["prompt"], None, rag_data
                )
                append_row(
                    args.output,
                    {
                        "run_id": run_id,
                        "timestamp": datetime.now(timezone.utc).isoformat(),
                        "model": model,
                        "condition": condition,
                        "item_id": item["id"],
                        "poc": item["poc"],
                        "variant": item["variant"],
                        "turn": 1,
                        "prompt": item["prompt"],
                        "response": response,
                        "rag_sources": sources,
                        "latency_seconds": round(time.monotonic() - started, 3),
                    },
                )
                completed.add(run_id)
            else:
                # Reconstruct history from the stored first turn for the one multi-turn POC.
                if item.get("follow_up"):
                    for line in args.output.read_text(encoding="utf-8").splitlines():
                        row = json.loads(line)
                        if row.get("run_id") == run_id:
                            history = [
                                {"role": "user", "content": row["prompt"]},
                                {"role": "assistant", "content": row["response"]},
                            ]
                            break

            if item.get("follow_up"):
                follow_id = f"{item['id']}::{condition}::turn2"
                if follow_id in completed:
                    continue
                started = time.monotonic()
                response, _history, sources = chat(
                    client, model, condition, item["follow_up"], history, rag_data
                )
                append_row(
                    args.output,
                    {
                        "run_id": follow_id,
                        "timestamp": datetime.now(timezone.utc).isoformat(),
                        "model": model,
                        "condition": condition,
                        "item_id": item["id"],
                        "poc": item["poc"],
                        "variant": "held_out_trap_turn",
                        "turn": 2,
                        "prompt": item["follow_up"],
                        "response": response,
                        "rag_sources": sources,
                        "latency_seconds": round(time.monotonic() - started, 3),
                    },
                )
                completed.add(follow_id)

    print(f"Wrote {len(completed)} completed runs to {args.output}")


if __name__ == "__main__":
    main()
